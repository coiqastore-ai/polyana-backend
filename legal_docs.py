# Document version is injected at render time, not from env.
_DOC_VERSION_PLACEHOLDER = "{{DOCUMENT_VERSION}}"
_DOC_DATE_PLACEHOLDER = "{{DOCUMENT_DATE}}"


def _resolve_placeholders(text: str, version: str = "1.0") -> str:
    """Replace all known placeholders with env values."""
    now = datetime.now(timezone.utc).strftime("%d.%m.%Y")
    for placeholder, env_key in _PLACEHOLDER_ENV_MAP.items():
        value = os.environ.get(env_key, "")
        text = text.replace(placeholder, value)
    text = text.replace(_DOC_VERSION_PLACEHOLDER, version)
    text = text.replace(_DOC_DATE_PLACEHOLDER, now)
    return text


def content_hash(text: str) -> str:
    """SHA-256 hash of document content."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def check_legal_config() -> list[str]:
    """Return list of missing env var names. Empty = all configured."""
    missing = []
    for _placeholder, env_key in _PLACEHOLDER_ENV_MAP.items():
        if not os.environ.get(env_key):
            missing.append(env_key)
    return missing


